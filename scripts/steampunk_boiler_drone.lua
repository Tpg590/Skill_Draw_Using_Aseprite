sprite:saveCopyAs("output/aseprite/steampunk_boiler_drone.aseprite")
sprite:saveCopyAs("output/gif/steampunk_boiler_drone.gif")

local totalFrames = #sprite.frames
local sheetSprite = Sprite(width * totalFrames, height, ColorMode.RGB)
local sheetImage = sheetSprite.cels[1].image
for i = 1, totalFrames do
    local frameCel = layer:cel(i)
    if frameCel then
        sheetImage:drawImage(frameCel.image, Point((i - 1) * width, 0))
    end
end
sheetSprite:saveCopyAs("output/Sheet/steampunk_boiler_drone_sheet.png")
sheetSprite:close()
sprite:close()
