-- 48x48 Stardew Valley Animated Swinging Spiked Ball on Interlocking 4-Link Chain (6 FPS)
-- 4 Frames Cycle: Swing Left -> Passing Center (C-curve Follow-Through) -> Swing Right -> Return Center (Inverted C-curve)
-- Strict Technical Requirements: Follow-Through chain inertia, Locked Pivot Point (24, 7), 10 o'clock static highlight

local width = 48
local height = 48
local fps = 6
local frameDuration = 1.0 / fps

local sprite = Sprite(width, height, ColorMode.RGB)
local layer = sprite.layers[1]
layer.name = "Main"
sprite.frames[1].duration = frameDuration
local image = sprite.cels[1].image

-- 1. Palette: Stardew Valley Warm & Soft Palette (NO #000000!)
local PALETTE = {
    ["."] = nil,
    ["S"] = "#26182c", -- Bóng tiếp đất mềm mại (Ground contact shadow, alpha 130)
    ["#"] = "#261e2c", -- Viền sẫm nâu tím ấm mềm (Soft dark purple-charcoal outline, NO #000000!)
    ["H"] = "#d8e2ea", -- Điểm phản quang 10h & gờ sáng bạc (10 o'clock Specular Glint)
    ["A"] = "#9aa6b6", -- Sắt xám sáng ấm (Lit metal highlight)
    ["B"] = "#626e80", -- Thân sắt xám chính (Metal body midtone)
    ["C"] = "#384050", -- Hốc rãnh bóng tối kim loại (Metal deep shadow / crevice)
    ["K"] = "#a49486", -- Đá xà ngang sáng (Warm stone beam highlight)
