-- 1. Palette: Stardew Valley Warm Terracotta Palette (Soft outlines, NO #000000!)
local PALETTE = {
    ["."] = nil,
    ["#"] = "#3c180e", -- Viền nâu đất nung sẫm mềm (Soft dark terracotta outline, NO #000000)
    ["S"] = "#26141c", -- Bóng tiếp đất mềm mại (Ground contact shadow, alpha 130)
    ["A"] = "#f09a56", -- Đất nung sáng (Warm terracotta highlight)
    ["B"] = "#c8642a", -- Đất nung nền (Rich baked terracotta midtone)
    ["C"] = "#7a3216", -- Đất nung tối (Deep burnt sienna shadow)
    ["D"] = "#ffd28a", -- Men gốm vàng kem trang trí (Ceramic ornamental band & rim)
    ["E"] = "#9c481e", -- Lớp gốm vát cạnh trong (Inner ceramic fracture bevel)
    ["Z"] = "#280e08"  -- Vết nứt rạn va đập sâu (Deep fracture crack crevice)
}

-- 2. Render function (with explicit transparent pixel clearing)
local function renderGrid(img, gridData, pal)
    for y = 1, #gridData do
        local line = gridData[y]
        for x = 1, #line do
            local char = line:sub(x, x)
            local hex = pal[char]
            if hex then
                local h = hex:gsub("#", "")
                local r = tonumber(h:sub(1, 2), 16) or 0
                local g = tonumber(h:sub(3, 4), 16) or 0
                local b = tonumber(h:sub(5, 6), 16) or 0
                local a = (char == "S") and 130 or 255
                img:drawPixel(x - 1, y - 1, Color{ r = r, g = g, b = b, a = a })
            else
                img:drawPixel(x - 1, y - 1, Color{ r = 0, g = 0, b = 0, a = 0 })
            end
        end
    end
end

