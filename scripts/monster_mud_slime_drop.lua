sprite:saveCopyAs("output/aseprite/monster_mud_slime_drop.aseprite")
sprite:saveCopyAs("output/gif/monster_mud_slime_drop.gif")

local totalFrames = #sprite.frames
local sheetSprite = Sprite(width * totalFrames, height, ColorMode.RGB)
local sheetImage = sheetSprite.cels[1].image
for i = 1, totalFrames do
    local frameCel = layer:cel(i)
    if frameCel then
        sheetImage:drawImage(frameCel.image, Point((i - 1) * width, 0))
    end
end
sheetSprite:saveCopyAs("output/Sheet/monster_mud_slime_drop_sheet.png")
sheetSprite:close()
sprite:close()
