    ["."] = nil,
    ["#"] = "#100e14", -- Viền sẫm Terraria
    ["S"] = "#120e18", -- Soft cast shadow (Alpha 140)
    ["A"] = "#7c8494", -- F1: Đá phiến sáng (Stone highlight)
    ["B"] = "#4a505e", -- F2: Đá phiến nền (Stone midtone)
    ["C"] = "#262a34", -- F3: Đá phiến tối (Stone shadow)
    ["D"] = "#9aa0b0", -- I1: Sắt lạnh sáng (Iron highlight)
    ["E"] = "#545a68", -- I2: Sắt lạnh nền (Iron midtone)
    ["F"] = "#2a2e38", -- I3: Sắt lạnh tối (Iron shadow)
    ["G"] = "#e0b450", -- O1: Hắt sáng OSL vàng rực (OSL highlight)
    ["H"] = "#8a6428", -- O2: Hắt sáng OSL vàng ấm (OSL midtone)
    ["J"] = "#ffea90", -- L1: Lõi lửa vàng trắng (Core flame)
    ["K"] = "#fca820", -- L2: Ánh sáng đèn vàng rực (Lantern glow)
    ["L"] = "#d05a10", -- L3: Ngọn lửa cam sẫm (Deep orange flame)
    ["M"] = "#b4dce6"  -- G1: Phản quang kính đèn (Glass specular)
}

-- 2. Render function
local function renderGrid(img, gridData, pal)
    for y = 1, #gridData do
        local line = gridData[y]
        for x = 1, #line do
            local char = line:sub(x, x)
            local hex = pal[char]
            if hex then
                local h = hex:gsub("#", "")
                local r = tonumber(h:sub(1, 2), 16) or 0
                local g = tonumber(h:sub(3, 4), 16) or 0
                local b = tonumber(h:sub(5, 6), 16) or 0
                local a = (char == "S") and 140 or 255
                img:drawPixel(x - 1, y - 1, Color{ r = r, g = g, b = b, a = a })
            else
                img:drawPixel(x - 1, y - 1, Color{ r = 0, g = 0, b = 0, a = 0 })
            end
        end
    end
end

