import os
from design_energy_crystal_pillar import generate_frames, PALETTE, WIDTH, HEIGHT, NUM_FRAMES

def export_lua():
    frames = generate_frames()
    
    lua_code = []
    lua_code.append("-- ========================================================")
    lua_code.append("-- Energy Crystal Pillar Animation (FreeStyle 48x48)")
    lua_code.append("-- Output: 6 frames @ 6 FPS")
    lua_code.append("-- Rules applied: 2D_physics_fracture_destruction, optics_lighting,")
    lua_code.append("--                spatial_perspective, fluid_gas_vfx")
    lua_code.append("-- ========================================================")
    lua_code.append("")
    lua_code.append(f"local width = {WIDTH}")
    lua_code.append(f"local height = {HEIGHT}")
    lua_code.append("local fps = 6")
    lua_code.append("local frameDuration = 1.0 / fps")
    lua_code.append("")
    lua_code.append("local sprite = Sprite(width, height, ColorMode.RGB)")
    lua_code.append("local layer = sprite.layers[1]")
    lua_code.append('layer.name = "Crystal_Pillar"')
    lua_code.append("sprite.frames[1].duration = frameDuration")
    lua_code.append("")
    lua_code.append("local PALETTE = {")
    for k, v in PALETTE.items():
        if k == '.':
            continue
        lua_code.append(f'    ["{k}"] = Color{{ r = {v[0]}, g = {v[1]}, b = {v[2]}, a = {v[3]} }},')
    lua_code.append("}")
    lua_code.append("")
    lua_code.append("local frame_grids = {")
    for f_idx, frame in enumerate(frames):
        lua_code.append(f"    -- Frame {f_idx + 1}")
        lua_code.append("    {")
        for row in frame:
            row_str = "".join(row)
            lua_code.append(f'        "{row_str}",')
        lua_code.append("    },")
    lua_code.append("}")
    lua_code.append("")
    lua_code.append("local function renderGrid(img, gridData, pal)")
    lua_code.append("    for y = 1, #gridData do")
    lua_code.append("        local line = gridData[y]")
    lua_code.append("        for x = 1, #line do")
    lua_code.append("            local char = line:sub(x, x)")
    lua_code.append("            local color = pal[char]")
    lua_code.append("            if color then")
    lua_code.append("                img:drawPixel(x - 1, y - 1, color)")
    lua_code.append("            end")
    lua_code.append("        end")
    lua_code.append("    end")
    lua_code.append("end")
    lua_code.append("")
    lua_code.append("-- Render Frame 1")
    lua_code.append("local img1 = sprite.cels[1].image")
    lua_code.append("img1:clear()")
    lua_code.append("renderGrid(img1, frame_grids[1], PALETTE)")
    lua_code.append("")
    lua_code.append("-- Create and Render Frames 2 to 6")
    lua_code.append("for i = 2, #frame_grids do")
    lua_code.append("    local newFrame = sprite:newFrame()")
    lua_code.append("    newFrame.duration = frameDuration")
    lua_code.append("    local cel = layer:cel(i)")
    lua_code.append("    if not cel then")
    lua_code.append("        cel = sprite:newCel(layer, newFrame)")
    lua_code.append("    end")
    lua_code.append("    cel.image:clear()")
    lua_code.append("    renderGrid(cel.image, frame_grids[i], PALETTE)")
    lua_code.append("end")
    lua_code.append("")
    lua_code.append("os.execute('mkdir output\\\\Sheet 2>nul')")
    lua_code.append("os.execute('mkdir output\\\\gif 2>nul')")
    lua_code.append("os.execute('mkdir output\\\\aseprite 2>nul')")
    lua_code.append("")
    lua_code.append('sprite:saveCopyAs("output/aseprite/energy_crystal_pillar.aseprite")')
    lua_code.append('sprite:saveCopyAs("output/gif/energy_crystal_pillar.gif")')
    lua_code.append("")
    lua_code.append("local totalFrames = #sprite.frames")
    lua_code.append("local sheetSprite = Sprite(width * totalFrames, height, ColorMode.RGB)")
    lua_code.append("local sheetImage = sheetSprite.cels[1].image")
    lua_code.append("for i = 1, totalFrames do")
    lua_code.append("    local frameCel = layer:cel(i)")
    lua_code.append("    if frameCel then")
    lua_code.append("        sheetImage:drawImage(frameCel.image, Point((i - 1) * width, 0))")
    lua_code.append("    end")
    lua_code.append("end")
    lua_code.append('sheetSprite:saveCopyAs("output/Sheet/energy_crystal_pillar_sheet.png")')
    lua_code.append("sheetSprite:close()")
    lua_code.append("sprite:close()")
    lua_code.append('print("[XONG] energy_crystal_pillar animation rendered!")')
    
    os.makedirs('scripts', exist_ok=True)
    with open('scripts/energy_crystal_pillar.lua', 'w', encoding='utf-8') as f:
        f.write("\n".join(lua_code) + "\n")
    print("Exported scripts/energy_crystal_pillar.lua successfully.")

if __name__ == '__main__':
    export_lua()
